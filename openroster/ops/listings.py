"""LISTINGS.md: the upcoming opportunities as a Markdown table, so people browsing the repository on GitHub can see
them without opening the site. Regenerated by the "Update data" workflow after every scrape."""

from __future__ import annotations

from datetime import UTC, datetime
from zoneinfo import ZoneInfo

from ..config import ROOT
from ..model import Opportunity
from ..pipeline import store

LISTINGS = ROOT / "LISTINGS.md"
SITE = "https://openroster.vercel.app"
TYPE = {
    "hackathon": "Hackathon", "info_session": "Info session", "tech_talk": "Tech talk", "career_fair": "Career fair",
    "networking": "Networking", "workshop": "Workshop", "conference": "Conference",
    "case_competition": "Case competition", "early_career_program": "Program", "other": "Other",
}
ROLE = {"participant": "attend", "volunteer": "volunteer", "mentor": "mentor", "judge": "judge",
        "organizer_team": "organize", "workshop_lead": "run a workshop"}
LIMIT = 300


def _cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def _date(d: datetime, tz: str) -> str:
    return d.astimezone(ZoneInfo(tz)).strftime("%b %-d")


def row(o: Opportunity, now: datetime) -> str:
    deadlines = sorted(r.closes for r in o.roles if r.closes and r.closes >= now)
    deadline = _date(deadlines[0], o.timezone) if deadlines else "Not listed"
    where = "Online" if o.mode == "online" else ", ".join(x for x in (o.location.city, (o.location.region or "")[3:]) if x) or "TBA"
    ways = ", ".join(ROLE[r.role] for r in o.roles if r.status != "closed")
    return (f"| {deadline} | {_date(o.start, o.timezone)} | [{_cell(o.title)}]({SITE}/o/{o.id}/) | {_cell(o.organizer)} | "
            f"{TYPE.get(o.type, o.type)} | {_cell(where)} | {ways} |")


def write_listings(now: datetime | None = None) -> int:
    now = now or datetime.now(UTC)
    live = [o for o in store.load_records().values() if o.status not in ("needs_review", "cancelled")]
    live.sort(key=lambda o: o.sort_key())
    lines = [
        "# Upcoming opportunities",
        "",
        "Hackathons, info sessions, talks, career fairs, workshops, competitions and early-career programs for CS "
        f"students, soonest deadline first. Filter, subscribe to a calendar, or see details at {SITE}.",
        "",
        f"{len(live)} listed. This file updates every 6 hours. Something missing? "
        "[Add it](../../issues/new?template=submit-opportunity.yml).",
        "",
        "| Apply by | Starts | Opportunity | Organizer | Type | Where | Ways to take part |",
        "|---|---|---|---|---|---|---|",
        *[row(o, now) for o in live[:LIMIT]],
        "",
    ]
    if len(live) > LIMIT:
        lines.append(f"Showing the first {LIMIT}. The full list is on the site.")
    # The date line is left out on purpose so an unchanged list produces no commit.
    store.write_if_changed(LISTINGS, "\n".join(lines) + "\n")
    return len(live)
